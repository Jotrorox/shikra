/* mkembed.c -- turn text files into src/embed.c (DESIGN.md §2 "Embedding").
 * usage: mkembed FILE... > src/embed.c
 * Each file becomes a NULL-terminated array of string literals, each holding < 4000
 * bytes (C99 guarantees 4095 per literal), followed by a name -> text table sorted by
 * name. Output depends only on the names and contents: deterministic. Plain C99. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define CHUNK 3000 /* bytes per literal before we look for a line break; hard cap below */
#define HARD 3990

static int cmp(const void *a, const void *b) { return strcmp(*(char *const *)a, *(char *const *)b); }

static void emit_file(int idx, const char *name) {
    FILE *f = fopen(name, "rb");
    int c, prev = 0;
    long n = 0;
    if (!f) { fprintf(stderr, "mkembed: cannot open %s\n", name); exit(1); }
    printf("static const char *const e%d[] = {\n\"", idx);
    while ((c = getc(f)) != EOF) {
        if (c == 0) { fprintf(stderr, "mkembed: %s contains a NUL byte\n", name); exit(1); }
        if (c == '\n') fputs("\\n", stdout);
        else if (c == '\\') fputs("\\\\", stdout);
        else if (c == '"') fputs("\\\"", stdout);
        else if (c == '?' && prev == '?') fputs("\\?", stdout); /* no trigraphs */
        else if (c == '\t') fputs("\\t", stdout);
        else if (c < 0x20 || c >= 0x7F) printf("\\%03o", c);
        else putchar(c);
        prev = c;
        n++;
        if (c == '\n') {
            if (n >= CHUNK) { fputs("\",\n\"", stdout); n = 0; }
            else fputs("\"\n\"", stdout);
        } else if (n >= HARD) { fputs("\",\n\"", stdout); n = 0; prev = 0; }
    }
    fclose(f);
    printf("\",\n0};\n");
}

int main(int argc, char **argv) {
    int i, n = argc - 1;
    char **names = argv + 1;
    qsort(names, (size_t)n, sizeof *names, cmp);
    printf("/* GENERATED by tools/mkembed -- do not edit. Regenerate with `make`. */\n"
           "#include \"embed.h\"\n\n");
    for (i = 0; i < n; i++) {
        if (i > 0 && !strcmp(names[i], names[i - 1])) { fprintf(stderr, "mkembed: duplicate %s\n", names[i]); return 1; }
        emit_file(i, names[i]);
    }
    printf("\nconst embed_file embed_files[] = {\n");
    for (i = 0; i < n; i++) printf("    {\"%s\", e%d},\n", names[i], i);
    printf("    {0, 0}\n};\n");
    return 0;
}
