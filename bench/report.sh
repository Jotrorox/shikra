#!/bin/sh
# bench/report.sh -- merge the latest CSV of each series in bench/results/ into
# bench/RESULTS.md.
#
#   sh bench/report.sh            (or: bench/run.sh report)
#
# Series (CSV file name prefix = run.sh label):
#   chez, gambit                     safe reference implementations (as upstream)
#   shikra, shikra-unsafe            current Shikra runs; when absent, the frozen
#   shikra-baseline(-unsafe)         pre-optimizer baseline is used instead
#   chez-unsafe, gambit-unsafe       unsafe references (second table)
# Override the Shikra series with SHIKRA_LABEL=... / SHIKRA_UNSAFE_LABEL=...
# Times are the benchmark's own "Elapsed time" line (seconds); ratios > 1 mean
# Shikra is slower.
set -eu
DIR=$(cd "$(dirname "$0")" && pwd)
exec perl -x "$0" "$DIR"
#!perl
use strict;
use warnings;

my $dir = shift;
my $resdir = "$dir/results";
opendir(my $dh, $resdir) or die "no $resdir\n";
my @csvs = sort grep { /\.csv$/ } readdir($dh);
closedir($dh);

sub latest {
    my ($label) = @_;
    my @m = grep { /^\Q$label\E-\d{8}-\d{4}\.csv$/ } @csvs;
    return @m ? $m[-1] : undef;
}

sub load {
    my ($file) = @_;
    return undef unless defined $file;
    my %s = (file => $file, rows => {}, order => []);
    open(my $fh, '<', "$resdir/$file") or die "$file: $!\n";
    while (<$fh>) {
        chomp;
        if (/^# (\w+)=(.*)$/) { $s{meta}{$1} = $2; next; }
        next if /^benchmark,/ || /^\s*$/;
        my ($b, $st, $t, $w, $c, $rss, $size, $note) =
            /^([^,]*),([^,]*),([^,]*),([^,]*),([^,]*),([^,]*),([^,]*),"?(.*?)"?$/ or next;
        $s{rows}{$b} = { status => $st, time => $t, wall => $w, compile => $c,
                         rss => $rss, size => $size, note => $note };
        push @{$s{order}}, $b;
    }
    close($fh);
    return \%s;
}

my $shikra_label = $ENV{SHIKRA_LABEL}
    || (latest('shikra') ? 'shikra' : 'shikra-baseline');
my $shikra_u_label = $ENV{SHIKRA_UNSAFE_LABEL}
    || (latest('shikra-unsafe') ? 'shikra-unsafe' : 'shikra-baseline-unsafe');

my %S;
for my $l ('chez', 'gambit', 'chez-unsafe', 'gambit-unsafe',
           $shikra_label, $shikra_u_label, 'shikra-baseline') {
    $S{$l} = load(latest($l)) unless exists $S{$l};
}
my $chez = $S{chez}; my $gambit = $S{gambit};
my $sk = $S{$shikra_label}; my $sku = $S{$shikra_u_label};
my $base = ($shikra_label ne 'shikra-baseline') ? $S{'shikra-baseline'} : undef;

# Benchmark order: upstream order as recorded in the first available CSV.
my @order;
for my $s (grep { defined } ($chez, $gambit, $sk, $sku, $S{'chez-unsafe'}, $S{'gambit-unsafe'})) {
    my %seen = map { $_ => 1 } @order;
    push @order, grep { !$seen{$_} } @{$s->{order}};
}

sub ok { my ($s, $b) = @_; return $s && $s->{rows}{$b} && $s->{rows}{$b}{status} eq 'ok' && $s->{rows}{$b}{time} ne ''; }
sub t { my ($s, $b) = @_; return $s->{rows}{$b}{time}; }
sub cell {
    my ($s, $b) = @_;
    return 'n/a' unless $s;
    my $r = $s->{rows}{$b};
    return '' unless $r;
    return sprintf('%.2f', $r->{time}) if $r->{status} eq 'ok' && $r->{time} ne '';
    return $r->{status};
}
sub ratio {
    my ($a, $b, $bm) = @_;
    return '' unless ok($a, $bm) && ok($b, $bm) && t($b, $bm) > 0;
    return sprintf('%.2f', t($a, $bm) / t($b, $bm));
}
sub gmean {
    my @x = grep { $_ > 0 } @_;
    return undef unless @x;
    my $s = 0; $s += log($_) for @x;
    return exp($s / @x);
}
sub fmt { my ($x, $f) = @_; return defined $x ? sprintf($f // '%.2f', $x) : '-'; }
sub version { my ($s) = @_; return $s ? $s->{meta}{version} // '?' : 'not run'; }
sub counts {
    my ($s) = @_;
    return '' unless $s;
    my %c; $c{$s->{rows}{$_}{status}}++ for keys %{$s->{rows}};
    return join(', ', map { "$c{$_} $_" } sort { $c{$b} <=> $c{$a} || $a cmp $b } keys %c);
}
sub total {
    my ($s) = @_;
    return 0 unless $s;
    my $t = 0;
    for my $b (keys %{$s->{rows}}) {
        my $w = $s->{rows}{$b}{wall}; $t += $w if $w ne '';
        my $c = $s->{rows}{$b}{compile}; $t += $c if $c ne '';
    }
    return $t;
}

my @out;
my $date = `date '+%Y-%m-%d %H:%M %Z'`; chomp $date;
my $any = (grep { defined } values %S)[0];
push @out, "# r7rs-benchmarks results", "";
push @out, "Generated by `bench/report.sh` on $date from the newest CSV of each series in",
           "`bench/results/`. Times are seconds from each benchmark's own timing line",
           "(`current-jiffy` around the measured loop, excluding start-up and reading input);",
           "lower is better. Ratios are Shikra time / reference time (> 1 means Shikra is slower).",
           "A status replaces the time where a run did not finish correctly",
           "(`unsupported` = cannot run by design, see `bench/README.md`).", "";
push @out, "Machine: " . ($any ? $any->{meta}{machine} : '?') . ".  ",
           "Suite: " . ($any ? $any->{meta}{suite} : '?') . ", inputs as upstream, one run per benchmark,",
           "benchmarks run sequentially. The machine was not otherwise idle (other development work",
           "ran concurrently), so expect a few percent of noise.", "";

push @out, "## Series", "";
push @out, "| Column | CSV | Version | Flags | Date | Statuses | Wall + compile total |";
push @out, "|---|---|---|---|---|---|---|";
my @series = (['Chez', $chez], ['Gambit', $gambit],
              ["Shikra ($shikra_label)", $sk], ["Shikra unsafe ($shikra_u_label)", $sku]);
push @series, ['Shikra baseline', $base] if $base;
push @series, (['Chez unsafe', $S{'chez-unsafe'}], ['Gambit unsafe', $S{'gambit-unsafe'}]);
for my $p (@series) {
    my ($n, $s) = @$p;
    next unless $s;
    push @out, sprintf('| %s | `results/%s` | %s | %s | %s | %s | %.0f s |', $n, $s->{file},
        version($s), $s->{meta}{flags} // '', $s->{meta}{date} // '', counts($s), total($s));
}
push @out, "", "Limits (wall clock, per benchmark): run timeout=" . ($any ? $any->{meta}{timeout} : "?") . ".", "";

# ---- main table (safe) ----
push @out, "## Safe mode", "";
my @hdr = ('Benchmark', 'Chez', 'Gambit', 'Shikra', 'Shikra unsafe', 'Shikra/Chez', 'Shikra/Gambit', 'Shikra-unsafe/Chez');
push @hdr, ('Shikra baseline', 'Shikra/baseline') if $base;
push @hdr, ('Shikra binary KB', 'Shikra RSS MB');
push @out, '| ' . join(' | ', @hdr) . ' |';
push @out, '|' . join('|', ('---') x @hdr) . '|';
my (@common, @gm_c, @gm_g, @gm_s, @gm_su, @r_sc, @r_sg, @r_suc);
for my $b (@order) {
    my @row = ($b, cell($chez, $b), cell($gambit, $b), cell($sk, $b), cell($sku, $b),
               ratio($sk, $chez, $b), ratio($sk, $gambit, $b), ratio($sku, $chez, $b));
    push @row, (cell($base, $b), ratio($sk, $base, $b)) if $base;
    my $r = $sk ? $sk->{rows}{$b} : undef;
    push @row, ($r && $r->{size} ne '' ? sprintf('%.0f', $r->{size} / 1024) : '',
                $r && $r->{rss} ne '' ? sprintf('%.1f', $r->{rss} / 1024) : '');
    push @out, '| ' . join(' | ', @row) . ' |';
    if (ok($chez, $b) && ok($gambit, $b) && (!$sk || ok($sk, $b)) && (!$sku || ok($sku, $b))) {
        push @common, $b;
        push @gm_c, t($chez, $b); push @gm_g, t($gambit, $b);
        push @gm_s, t($sk, $b) if $sk;
        push @gm_su, t($sku, $b) if $sku;
        if ($sk) { push @r_sc, t($sk, $b) / t($chez, $b); push @r_sg, t($sk, $b) / t($gambit, $b); }
        push @r_suc, t($sku, $b) / t($chez, $b) if $sku;
    }
}
push @out, '| **geometric mean** (' . scalar(@common) . ' common) | ' . join(' | ',
    fmt(gmean(@gm_c)), fmt(gmean(@gm_g)), fmt(gmean(@gm_s)), fmt(gmean(@gm_su)),
    '**' . fmt(gmean(@r_sc)) . '**', '**' . fmt(gmean(@r_sg)) . '**', '**' . fmt(gmean(@r_suc)) . '**') .
    ($base ? ' | | ' : '') . ' | | |';
push @out, "";
push @out, "Geometric means are over the " . scalar(@common) .
    " benchmarks that every column of this table completed with status `ok`" .
    (@common ? ": " . join(', ', @common) : '') . ".", "";

# ---- unsafe table ----
my ($cu, $gu) = ($S{'chez-unsafe'}, $S{'gambit-unsafe'});
if ($cu || $gu) {
    push @out, "## Unsafe mode", "";
    push @out, "Chez at `optimize-level 3`, Gambit with `(declare (not safe))`, Shikra with `--unsafe`.", "";
    my @h = ('Benchmark', 'Chez unsafe', 'Gambit unsafe', 'Shikra unsafe', 'Shikra-unsafe/Chez-unsafe', 'Shikra-unsafe/Gambit-unsafe');
    push @out, '| ' . join(' | ', @h) . ' |';
    push @out, '|' . join('|', ('---') x @h) . '|';
    my (@c2, @a, @g2, @s2, @r1, @r2);
    for my $b (@order) {
        push @out, '| ' . join(' | ', $b, cell($cu, $b), cell($gu, $b), cell($sku, $b),
            ratio($sku, $cu, $b), ratio($sku, $gu, $b)) . ' |';
        if (ok($cu, $b) && ok($gu, $b) && (!$sku || ok($sku, $b))) {
            push @c2, $b; push @a, t($cu, $b); push @g2, t($gu, $b);
            if ($sku) { push @s2, t($sku, $b); push @r1, t($sku, $b) / t($cu, $b); push @r2, t($sku, $b) / t($gu, $b); }
        }
    }
    push @out, '| **geometric mean** (' . scalar(@c2) . ' common) | ' . join(' | ',
        fmt(gmean(@a)), fmt(gmean(@g2)), fmt(gmean(@s2)),
        '**' . fmt(gmean(@r1)) . '**', '**' . fmt(gmean(@r2)) . '**') . ' |';
    push @out, "";
}

# ---- notes for non-ok entries ----
push @out, "## Non-ok entries", "";
for my $p (@series) {
    my ($n, $s) = @$p;
    next unless $s;
    my @bad = grep { $s->{rows}{$_}{status} ne 'ok' } @{$s->{order}};
    next unless @bad;
    push @out, "**$n**", "";
    for my $b (@bad) {
        my $r = $s->{rows}{$b};
        my $note = $r->{note}; $note =~ s/\|/\\|/g;
        push @out, "- `$b`: $r->{status}" . ($note ne '' ? " -- $note" : '');
    }
    push @out, "";
}
push @out, "Failure details for Shikra: `bench/BASELINE-FAILURES.md`; classification of",
           "unsupported benchmarks: `bench/README.md`.";

open(my $fh, '>', "$dir/RESULTS.md") or die "RESULTS.md: $!\n";
print $fh join("\n", @out), "\n";
close($fh);
print "wrote $dir/RESULTS.md\n";
